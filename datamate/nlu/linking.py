"""[C3] Link the names in a plan's filters to values in the data. Work package G6.

A filter value as written ("coca", "tại quầy", "bình anh") is linked to a data value only when it clearly means one:
1. it equals a data value or a code once both are folded (no diacritics, telex typos undone, punctuation ignored);
2. else a data value written out in full in the question contains it, or shares most of its words: the questions are
   generated by inserting whole names, so "khách quách bình anh" read by the LLM as "bình anh", or "nghiêm mai hiếu"
   copied as "Nguyễn Mai Hiếu", still links to the name the question carries;
3. else the most similar data value, if it scores ≥ THRESHOLD and beats the next value by ≥ MARGIN.
A product name is also tried without a counting unit of the shop in front ("bình Gas Petrolimex 12kg", "xe 4m3 cát
xây tô"): the LLM sometimes copies the unit the question counts in.
Names of one value (a pharmacy of train writes 162 product names for 80 codes) count as one candidate. Channels and payment methods
link to a code (store, cash…) through assets/linking/synonyms.json, as shops write them as codes or as Vietnamese
words, sometimes both in one column; `matches` filters a column by any linked value. A value that is not linked stays
out of `plan.linked`, and [V] makes the question abstain.
"""
from __future__ import annotations

import json
import re
import unicodedata
import weakref
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import pandas as pd
from rapidfuzz import fuzz

from datamate.contracts import CanonicalDB

from .templates import tokens

SYNONYMS_FILE = Path(__file__).resolve().parents[2] / "assets" / "linking" / "synonyms.json"
THRESHOLD = 90.0
MARGIN = 5.0
CODED = frozenset({"channel", "payment_method"})  # linked to a code of synonyms.json, not to a data value

# field -> (table, column holding the name, column holding the value the metrics filter on; None = the name itself)
SOURCES: dict[str, list[tuple[str, str, str | None]]] = {
    "product": [("lines", "product_name", "product_key"), ("products", "product_name", "product_key"),
                ("lines", "product_key", "product_key"), ("products", "product_key", "product_key")],
    "product_group": [("products", "product_group", None), ("lines", "product_group", None)],
    "category": [("products", "category", None)],
    "product_line": [("products", "product_line", None)],
    "brand": [("products", "brand", None)],
    "active_ingredient": [("products", "active_ingredient", None)],
    "customer": [("customers", "customer_name", "customer_key"), ("customers", "customer_key", "customer_key"),
                 ("orders", "customer_name", "customer_key"), ("orders", "customer_key", "customer_key")],
    "customer_group": [("orders", "customer_group", None), ("customers", "customer_group", None)],
    "employee": [("orders", "employee", None), ("employees", "employee_name", "employee_key"),
                 ("employees", "employee_key", "employee_key")],
    "supplier": [("purchases", "supplier", None)],
    "vehicle_model": [("orders", "vehicle_model", None)],
    "plate": [("orders", "vehicle_plate", None)],
    "channel": [("orders", "channel", None)],
    "payment_method": [("orders", "payment_method", None), ("payments", "method", None)],
}
# the value a metric filters on must exist where it filters: an employee code from the staff list that no order
# carries (orders hold names) would filter every order out and answer 0
FILTERED_ON = {"employee": ("orders", "employee")}


def norm(text) -> str:
    """Folded words and numbers, telex typos undone, punctuation dropped: "Nước ép dưa hấu (L)" -> nuoc ep dua hau l."""
    return " ".join(tokens(str(text)))


@lru_cache(maxsize=1)
def synonyms() -> dict[str, dict[str, tuple[str, ...]]]:
    """field -> code -> its spellings (folded), the code itself included."""
    raw = json.loads(SYNONYMS_FILE.read_text(encoding="utf-8"))
    return {field: {code: tuple(dict.fromkeys(norm(w) for w in [code, *words])) for code, words in codes.items()}
            for field, codes in raw.items() if not field.startswith("_")}


def concept(field: str, text) -> str | None:
    """Code of a channel / payment spelling: the code or a synonym, alone or as whole words inside ("Thu hộ (COD)" ->
    cod). None when no code fits, or more than one."""
    padded = f" {norm(text)} "
    hits = {code for code, words in synonyms().get(field, {}).items() if any(f" {w} " in padded for w in words)}
    return hits.pop() if len(hits) == 1 else None


@dataclass(frozen=True)
class Link:
    value: str | None  # what the metrics filter on; None = not linked
    score: float
    how: str  # exact / question / fuzzy / tie / none


Candidates = dict[str, frozenset[str]]  # folded name -> the values it names


_CACHE: dict[int, tuple[weakref.ref, dict[str, Candidates]]] = {}


def candidates(field: str, db: CanonicalDB) -> Candidates:
    """Names the data has for a filter field, folded, each with the value(s) it stands for. Cached per db."""
    ref, per_field = _CACHE.get(id(db), (None, None))
    if ref is None or ref() is not db:
        per_field = {}
        _CACHE[id(db)] = (weakref.ref(db), per_field)
    if field not in per_field:
        per_field[field] = _collect(field, db)
    return per_field[field]


UNIT_SOURCES = [("lines", "unit"), ("unit_conversions", "unit"), ("products", "base_unit"), ("purchases", "unit")]


def units(db: CanonicalDB) -> tuple[str, ...]:
    """Counting units the shop writes (folded), longest first. Cached per db."""
    candidates("product", db)  # creates the cache entry of this db
    per_field = _CACHE[id(db)][1]
    if "_units" not in per_field:
        found = set()
        for table, col in UNIT_SOURCES:
            df = db.table(table)
            if df is not None and col in df.columns:
                found |= {norm(u) for u in df[col].dropna().astype(str).unique()}
        per_field["_units"] = tuple(sorted((u for u in found if u), key=lambda u: (-len(u), u)))
    return per_field["_units"]


GREEK = {"α": "alpha", "β": "beta", "γ": "gamma"}  # "Wave α": norm() drops the letter


def _greek(spelling) -> str:
    s = str(spelling)
    for letter, word in GREEK.items():
        s = s.replace(letter, f" {word} ")
    return s


def model_words(spelling) -> list[str]:
    """A model name's words, folded without undoing telex: "Air Blade" is "air blade", not the "ai" of "ải"."""
    s = unicodedata.normalize("NFD", _greek(spelling).lower().replace("đ", "d"))
    return re.findall(r"[a-z]+|\d+", "".join(ch for ch in s if unicodedata.category(ch) != "Mn"))


@lru_cache(maxsize=256)
def model_lines(spellings: frozenset[str]) -> dict[str, str | None]:
    """§6 Sửa xe "tên dòng xe chỉ khác hoa/thường hoặc ghi tắt là cùng một dòng": each spelling of a ledger's vehicle
    models -> the line it names (the line's longest spelling), None when it may name two lines ("Wave" beside Wave
    Alpha and Wave RSX). A short form is the same letters ("shmode", "SH mode"), some of the words of a longer
    spelling ("Vision" of Vision 110, "Alpha" of Wave Alpha), its initials ("AB" of Air Blade) or its start ("Ex" of
    Exciter)."""
    words = {s: model_words(s) for s in spellings}
    compact = {s: "".join(w) for s, w in words.items()}
    kw: dict[str, list[str]] = {}  # letters -> the most words any spelling of them has ("air blade" for "airblade")
    for s, c in compact.items():
        if c and len(words[s]) > len(kw.get(c, [])):
            kw[c] = words[s]

    def short_of(a: str, b: str) -> bool:
        wa, wb = kw[a], kw[b]
        initials = "".join(w[0] for w in wb if w.isalpha())
        return len(a) < len(b) and (set(wa) < set(wb) or (len(a) >= 2 and len(wb) >= 2 and a == initials)
                                    or (len(a) >= 2 and b.startswith(a)))

    parents = {a: [b for b in kw if b != a and short_of(a, b)] for a in kw}

    def roots(a: str) -> set[str]:
        return {a} if not parents[a] else set().union(*(roots(b) for b in parents[a]))

    label: dict[str, str] = {}  # a line's name: its first spelling of the most words, by sort order
    for s in sorted(spellings, key=lambda s: (-len(words[s]), s)):
        label.setdefault(compact[s], s)
    out: dict[str, str | None] = {}
    for s, c in compact.items():
        r = roots(c) if c else set()
        out[s] = label[next(iter(r))] if len(r) == 1 else None
    return out


def ledger_lines(column: pd.Series) -> pd.Series:
    """The line of each row of a vehicle model column (None: blank, or a spelling of two lines)."""
    lines = model_lines(frozenset(column.dropna().astype(str)))
    return column.map(lambda v: lines.get(str(v)) if isinstance(v, str) else None)


def _collect(field: str, db: CanonicalDB) -> Candidates:
    if field == "vehicle_model":  # every spelling of a line names the line (§6 Sửa xe)
        o = db.table("orders")
        if o is None or "vehicle_model" not in o.columns:
            return {}
        out_lines: dict[str, set[str]] = {}
        for spelling, line in model_lines(frozenset(o["vehicle_model"].dropna().astype(str))).items():
            if line is not None and (key := norm(_greek(spelling))):  # as link_value folds the question's name
                out_lines.setdefault(key, set()).add(line)
        return {k: frozenset(v) for k, v in out_lines.items()}
    out: dict[str, set[str]] = {}
    allowed = None
    if field in FILTERED_ON:
        t, c = FILTERED_ON[field]
        df = db.table(t)
        allowed = set(df[c].dropna().astype(str)) if df is not None and c in df.columns else set()
    for table, name_col, value_col in SOURCES.get(field, []):
        df = db.table(table)
        if df is None or name_col not in df.columns or (value_col and value_col not in df.columns):
            continue
        cols = [name_col] if value_col in (None, name_col) else [name_col, value_col]
        for row in df[cols].dropna().astype(str).drop_duplicates().itertuples(index=False):
            name, value = row[0], row[-1]
            if field in CODED:
                value = concept(field, name)
            if value is None or not name.strip() or (allowed is not None and value not in allowed):
                continue
            key = norm(name)
            if key:
                out.setdefault(key, set()).add(value)
    return {k: frozenset(v) for k, v in out.items()}


def score(written: str, name: str) -> float:
    """Similarity of two folded names, 0–100; extra or missing words cost (token_sort_ratio), so a name contained in
    a longer one ("bia tiger" in "bia tiger bac lon") is not a match by itself."""
    return fuzz.token_sort_ratio(written, name)


def _one(names: list[str], cands: Candidates, how: str) -> Link:
    values = set().union(*(cands[n] for n in names))
    return Link(values.pop(), 100.0, how) if len(values) == 1 else Link(None, 100.0, "tie")


def _shared_words(a: str, b: str) -> int:
    return len({t for t in a.split() if t.isalpha()} & {t for t in b.split() if t.isalpha()})


# One thing, a northern and a southern word (public 06/11: "Lạc rang muối 200g" for the shop's "Đậu phộng rang muối
# 200g", "Đậu phụ rán giòn" for "Đậu hũ chiên giòn"). Replaced with their diacritics only: "lạc" is not "lắc"
# ("khoai tây lắc"), which folding would merge.
DIALECT = (("đậu phụ", "đậu hũ"), ("lạc", "đậu phộng"), ("rán", "chiên"), ("vừng", "mè"), ("ngô", "bắp"),
           ("mì chính", "bột ngọt"), ("lợn", "heo"), ("dứa", "thơm"), ("dưa chuột", "dưa leo"), ("mướp đắng", "khổ qua"),
           ("xì dầu", "nước tương"), ("hoa quả", "trái cây"), ("sắn", "khoai mì"), ("thìa", "muỗng"),
           # run10 (06/11): "cháo ngao" / "cháo nghêu", "cá tràu" (miền Trung) / "cá lóc", "cát xây trát" / "cát xây
           # tô", "găng tay" / "bao tay"
           ("ngao", "nghêu"), ("cá tràu", "cá lóc"), ("cá quả", "cá lóc"), ("trát", "tô"), ("găng tay", "bao tay"))


ONE_WAY = frozenset({"trát"})  # "tô" is also a bowl ("tô phở"): never read back as "trát"


def dialects(written) -> list[str]:
    """The written name in the southern words, and in the northern ones, when it has words of the other side."""
    text = unicodedata.normalize("NFC", str(written).lower())
    out = []
    for pairs in (DIALECT, tuple((s, n) for n, s in DIALECT if n not in ONE_WAY)):
        t = text
        for a, b in pairs:
            t = re.sub(rf"(?<!\w){re.escape(a)}(?!\w)", b, t)
        if t != text:
            out.append(t)
    return out


def link_value(field: str, written, question: str, cands: Candidates, units: tuple[str, ...] = ()) -> Link:
    """The data value a filter value names, by the steps of the module doc. `units`: the shop's counting units
    (folded, longest first), tried off the front of a product name."""
    if field in CODED:
        code = concept(field, written)
        present = {v for vs in cands.values() for v in vs}
        return Link(code, 100.0, "exact") if code is not None and code in present else Link(None, 0.0, "none")
    w = norm(written)
    if not w or not cands:
        return Link(None, 0.0, "none")
    variants = [w] + [w[len(u) + 1:] for u in units if w.startswith(u + " ")][:1]
    variants += [v for v in (norm(d) for d in dialects(written)) if v and v not in variants]
    for v in variants:
        if v in cands:
            return _one([v], cands, "exact")
    q = f" {norm(question)} "
    in_question = [n for n in cands if f" {n} " in q]
    in_question = [n for n in in_question if not any(n != m and f" {n} " in f" {m} " for m in in_question)]
    for v in variants:  # a name of the question contains what the LLM wrote
        inside = [n for n in in_question if f" {v} " in f" {n} "]
        if inside:
            return _one(inside, cands, "question")
    for v in variants:  # what the LLM wrote shares most words with a name of the question
        near = [n for n in in_question if _shared_words(v, n) >= max(2, len(v.split()) / 2)]
        if near:
            return _one(near, cands, "question")
    best: dict[str, float] = {}
    for name, values in cands.items():
        s = max(score(v, name) for v in variants)
        for v in values:
            best[v] = max(best.get(v, 0.0), s)
    ranked = sorted(best.items(), key=lambda kv: (-kv[1], kv[0]))
    top, s1 = ranked[0]
    s2 = ranked[1][1] if len(ranked) > 1 else 0.0
    if s1 >= THRESHOLD and s1 - s2 >= MARGIN:
        return Link(top, s1, "fuzzy")
    return Link(None, s1, "tie" if s1 >= THRESHOLD else "none")


def matches(field: str, column: pd.Series, value: str) -> pd.Series:
    """Rows of a data column that a linked value selects: by code for channels and payment methods (a column may mix
    "cash" and "Tiền mặt"), else by equality."""
    if field in CODED:
        codes = {v: concept(field, v) for v in column.dropna().unique()}  # once per spelling, not per row
        return column.map(codes).eq(value)
    if field == "vehicle_model":  # §6 Sửa xe: "tên dòng xe chỉ khác hoa/thường hoặc ghi tắt là cùng một dòng"
        return ledger_lines(column).eq(value) & column.notna()
    return column.astype(str).eq(value) & column.notna()
